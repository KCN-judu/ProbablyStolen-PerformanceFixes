// Usage: GenProbe.exe <Assembly-CSharp.dll> <out.cs>
// Lists public, non-generic game types that declare Update/LateUpdate/FixedUpdate (MonoBehaviours) or a parameterless
// Validate(), as C# typeof(...) entries the profiler can patch without reflecting over unknown types.
using System; using System.IO; using System.Linq; using System.Collections.Generic; using Mono.Cecil;
class G {
  static bool IsMono(TypeDefinition t) {
    for (var b = t.BaseType; b != null; ) {
      if (b.FullName == "UnityEngine.MonoBehaviour") return true;
      TypeDefinition d; try { d = b.Resolve(); } catch { return false; }
      if (d == null) return false; b = d.BaseType;
    }
    return false;
  }
  // The game's mod loader, mod security and Steam integration may not be patched by mods; leave them out.
  static bool Allowed(TypeDefinition t) {
    var n = t.Name;
    return !(n.StartsWith("Mod") || n.StartsWith("Steam") || n.StartsWith("Workshop") || n.Contains("Trust"));
  }
  static bool Visible(TypeDefinition t) {
    if (!Allowed(t)) return false;
    for (var x = t; x != null; x = x.DeclaringType) if (!(x.IsPublic || x.IsNestedPublic)) return false;
    return !t.HasGenericParameters && !t.IsInterface && t.Name.IndexOf('<') < 0;
  }
  static string Name(TypeDefinition t) { return "global::" + t.FullName.Replace('/', '.'); }
  static void Main(string[] a) {
    var res = new DefaultAssemblyResolver(); res.AddSearchDirectory(Path.GetDirectoryName(a[0]));
    var asm = AssemblyDefinition.ReadAssembly(a[0], new ReaderParameters { AssemblyResolver = res });
    var frame = new List<string>(); var validate = new List<string>();
    foreach (var t in asm.MainModule.GetTypes().Where(Visible).OrderBy(x => x.FullName)) {
      bool mono = IsMono(t);
      foreach (var m in t.Methods.Where(x => x.HasBody && !x.IsStatic && x.Parameters.Count == 0 && !x.HasGenericParameters)) {
        if (mono && (m.Name == "Update" || m.Name == "LateUpdate" || m.Name == "FixedUpdate"))
          frame.Add("            P(() => typeof(" + Name(t) + ").GetMethod(\"" + m.Name + "\", F, null, System.Type.EmptyTypes, null));");
        if (m.Name == "Validate") validate.Add("            P(() => typeof(" + Name(t) + ").GetMethod(\"Validate\", F, null, System.Type.EmptyTypes, null));");
      }
    }
    using (var w = new StreamWriter(a[1])) {
      w.WriteLine("// Generated by tools/GenProbe.cs from the game's Assembly-CSharp.dll. Regenerate after a game update.");
      w.WriteLine("namespace PerformanceFixes\n{\n    static partial class Profiler\n    {\n        static void AddTargets()\n        {");
      w.WriteLine("            // Per-frame callbacks (" + frame.Count + ")");
      foreach (var l in frame) w.WriteLine(l);
      w.WriteLine("            // Layout passes (" + validate.Count + ")");
      foreach (var l in validate) w.WriteLine(l);
      w.WriteLine("        }\n    }\n}");
    }
    Console.WriteLine(frame.Count + " frame callbacks, " + validate.Count + " validate methods");
  }
}
