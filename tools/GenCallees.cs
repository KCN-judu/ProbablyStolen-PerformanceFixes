// Usage: GenCallees.exe <Assembly-CSharp.dll> <out.cs> <depth> <Type::Method>...
// Lists the game methods reachable from the given roots (calls inside Assembly-CSharp, up to <depth> levels) as
// typeof(X).GetMethod(...) entries for the profiler. Skips the mod loader, Steam and anything not nameable in C#.
using System; using System.IO; using System.Linq; using System.Text; using System.Collections.Generic;
using Mono.Cecil; using Mono.Cecil.Cil;
class G {
  // The game's main module, set in Main; used to keep only calls that stay inside Assembly-CSharp.
  static ModuleDefinition mod;
  // Whether the type can be written in C# source from another assembly: all its declaring types are public and it is not
  // compiler-generated.
  static bool Visible(TypeReference r) {
    if (r is ByReferenceType) return Visible(((ByReferenceType)r).ElementType);
    if (r is ArrayType) return Visible(((ArrayType)r).ElementType);
    if (r is GenericParameter || r.IsPointer) return false;
    var gi = r as GenericInstanceType;
    if (gi != null) return Visible(gi.ElementType) && gi.GenericArguments.All(Visible);
    TypeDefinition d; try { d = r.Resolve(); } catch { return false; }
    if (d == null) return false;
    for (var x = d; x != null; x = x.DeclaringType) if (!(x.IsPublic || x.IsNestedPublic)) return false;
    return d.Name.IndexOf('<') < 0;
  }
  // C# spelling of a type for the generated source (by-ref types lose the ref; MakeByRefType is added in TypeOf).
  static string Cs(TypeReference r) {
    if (r is ByReferenceType) return Cs(((ByReferenceType)r).ElementType);
    if (r is ArrayType) return Cs(((ArrayType)r).ElementType) + "[]";
    var gi = r as GenericInstanceType;
    if (gi != null) {
      var n = gi.ElementType.FullName; n = n.Substring(0, n.IndexOf('`'));
      return "global::" + n.Replace('/', '.') + "<" + string.Join(", ", gi.GenericArguments.Select(Cs)) + ">";
    }
    return "global::" + r.FullName.Replace('/', '.');
  }
  // The typeof(...) expression that selects the overload in GetMethod.
  static string TypeOf(TypeReference r) {
    var t = "typeof(" + Cs(r) + ")";
    return r is ByReferenceType ? t + ".MakeByRefType()" : t;
  }
  // The game's mod loader, mod security and Steam integration may not be patched by mods; leave them out.
  static bool Allowed(TypeDefinition t) {
    var n = t.Name;
    return !(n.StartsWith("Mod") || n.StartsWith("Steam") || n.StartsWith("Workshop") || n.Contains("Trust"));
  }
  // Breadth-first walk of the call graph from the roots, one level per loop pass, then one line per usable method.
  static void Main(string[] a) {
    var res = new DefaultAssemblyResolver(); res.AddSearchDirectory(Path.GetDirectoryName(Path.GetFullPath(a[0])));
    var asm = AssemblyDefinition.ReadAssembly(a[0], new ReaderParameters { AssemblyResolver = res });
    mod = asm.MainModule;
    int depth = int.Parse(a[2]);
    var all = mod.GetTypes().SelectMany(t => t.Methods).ToList();
    var seen = new HashSet<MethodDefinition>(); var frontier = new List<MethodDefinition>();
    for (int i = 3; i < a.Length; i++) {
      var p = a[i].Split(new[] { "::" }, StringSplitOptions.None);
      frontier.AddRange(all.Where(m => m.DeclaringType.FullName == p[0] && m.Name == p[1]));
    }
    foreach (var m in frontier) seen.Add(m);
    for (int d = 0; d < depth; d++) {
      var next = new List<MethodDefinition>();
      foreach (var m in frontier.Where(x => x.HasBody))
        foreach (var ins in m.Body.Instructions)
          if (ins.OpCode == OpCodes.Call || ins.OpCode == OpCodes.Callvirt || ins.OpCode == OpCodes.Newobj) {
            var mr = ins.Operand as MethodReference; if (mr == null || mr.Module != mod) continue;
            MethodDefinition md; try { md = mr.Resolve(); } catch { continue; }
            if (md != null && md.Module == mod && seen.Add(md)) next.Add(md);
          }
      frontier = next;
    }
    // Skipped: constructors, generic and abstract methods, properties and compiler-generated names, since the profiler
    // finds methods by name and parameter types.
    var lines = new List<string>();
    foreach (var m in seen.OrderBy(x => x.DeclaringType.FullName).ThenBy(x => x.Name)) {
      var t = m.DeclaringType;
      if (!m.HasBody || m.IsConstructor || m.IsAbstract || m.HasGenericParameters || t.HasGenericParameters) continue;
      if (!Visible(t) || !Allowed(t) || !m.Parameters.All(p => Visible(p.ParameterType))) continue;
      if (m.Name.StartsWith("get_") || m.Name.StartsWith("set_") || m.Name.StartsWith("<")) continue;
      var args = m.Parameters.Count == 0 ? "System.Type.EmptyTypes"
        : "new System.Type[] { " + string.Join(", ", m.Parameters.Select(p => TypeOf(p.ParameterType))) + " }";
      lines.Add("            P(() => typeof(" + Cs(t) + ").GetMethod(\"" + m.Name + "\", FS, null, " + args + ", null));");
    }
    using (var w = new StreamWriter(a[1])) {
      w.WriteLine("// Generated by tools/GenCallees.cs: what the roots below call, " + depth + " levels deep. Regenerate after a game update.");
      w.WriteLine("// Roots: " + string.Join(", ", a.Skip(3)));
      w.WriteLine("namespace PerformanceFixes\n{\n    static partial class Profiler\n    {\n        static void AddCallees()\n        {");
      foreach (var l in lines) w.WriteLine(l);
      w.WriteLine("        }\n    }\n}");
    }
    Console.WriteLine(lines.Count + " callees");
  }
}
